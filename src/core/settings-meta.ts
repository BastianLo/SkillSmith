export function groupOf(path: string): SettingsGroup {
  for (const g of SETTINGS_GROUPS) {
    for (const m of g.match) if (m.endsWith(".") ? path.startsWith(m) : path === m || path.startsWith(`${m}.`)) return g
  }
  return SETTINGS_GROUPS[0]
}

